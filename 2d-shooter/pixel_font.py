class PixelFont:
    def __init__(self, state, batch="ui_text"):
        self.state = state
        self.batch = batch
        self.groups = {}
        self.signatures = {}

    def clear(self, key):
        for entity_id in self.groups.pop(key, []):
            self.state.destroy(entity_id)
        self.signatures.pop(key, None)

    def clear_all(self):
        for key in list(self.groups):
            self.clear(key)

    @staticmethod
    def measure(text, scale):
        lines = text.upper().split("\n")
        width = max((len(line) * 6 - 1 for line in lines), default=0) * scale
        height = max(0, len(lines) * 8 - 1) * scale
        return width, height

    def set_text(self, key, text, x, y, scale, color, center=False):
        signature = (text, x, y, scale, color, center)
        if self.signatures.get(key) == signature:
            return
        self.clear(key)
        text = text.upper()
        width, _ = self.measure(text, scale)
        origin_x = x - width / 2 if center else x
        ids = []
        r, g, b = color
        for line_index, line in enumerate(text.split("\n")):
            line_width = (len(line) * 6 - 1) * scale
            line_x = x - line_width / 2 if center else origin_x
            for char_index, char in enumerate(line):
                glyph = GLYPHS.get(char, GLYPHS[" "])
                for row, pattern in enumerate(glyph):
                    for column, pixel in enumerate(pattern):
                        if pixel == "1":
                            ids.append(self.state.spawn(
                                self.batch,
                                x=line_x + (char_index * 6 + column) * scale + scale / 2,
                                y=y + (line_index * 8 + row) * scale + scale / 2,
                                r=r, g=g, b=b, a=255,
                                width=scale, height=scale,
                            ))
        self.groups[key] = ids
        self.signatures[key] = signature
